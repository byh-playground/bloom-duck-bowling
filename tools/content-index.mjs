import { readFile, readdir, writeFile } from 'node:fs/promises';

const ROOT = new URL('../src/content/', import.meta.url);
const INDEX = new URL('index.mjs', ROOT);
const TYPES = [
    ['maps', 'mapDefinitions'],
    ['bowlers', 'bowlerDefinitions'],
];
const check = process.argv.includes('--check');
const imports = [];
const exports = [];

for (const [directory, name] of TYPES) {
    const files = (await readdir(new URL(directory + '/', ROOT), { withFileTypes: true }))
        .filter((entry) => entry.isFile() && entry.name.endsWith('.mjs'))
        .map((entry) => entry.name)
        .sort();
    if (!files.length) throw new Error('No content definitions in ' + directory);
    const names = files.map((file, index) => {
        if (!/^[a-z][a-z0-9-]*\.mjs$/.test(file))
            throw new Error('Invalid content file name: ' + file);
        const binding = name + index;
        imports.push('import ' + binding + " from './" + directory + '/' + file + "';");
        return '    ' + binding + ',';
    });
    exports.push('export const ' + name + ' = Object.freeze([\n' + names.join('\n') + '\n]);');
}
const source = ['// Generated by npm run content:index.', ...imports, '', ...exports, ''].join(
    '\n',
);
if (check) {
    const current = await readFile(INDEX, 'utf8');
    if (current.replaceAll('\r\n', '\n') !== source) {
        throw new Error('Content index is stale. Run npm run content:index.');
    }
} else {
    await writeFile(INDEX, source);
}
